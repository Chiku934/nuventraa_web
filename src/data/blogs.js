export function getBlogBySlug(slug) {
  return blogsData.find((b) => b.slug === slug) || null;
}

export function getRecentBlogs(limit = 4, excludeId = null) {
  return blogsData.filter((b) => b.id !== excludeId).slice(0, limit);
}

export function getAllCategories() {
  const cats = {};
  blogsData.forEach((b) => {
    cats[b.category] = (cats[b.category] || 0) + 1;
  });
  return Object.entries(cats).map(([name, count]) => ({ name, count }));
}

export function getAllTags() {
  const set = new Set();
  blogsData.forEach((b) => {
    b.tags.forEach((t) => set.add(t));
  });
  return Array.from(set);
}
